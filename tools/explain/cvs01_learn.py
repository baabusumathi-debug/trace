PRIMER = "The heart sits inside a sac whose outer fibrous layer barely stretches over minutes, so the pressure inside it depends on how fast fluid arrives, not only how much. The right heart fills at low pressure (a few mmHg), so it is the first chamber to be squeezed when pericardial pressure rises. Both ventricles share one septum inside one fixed sac, so whatever fills the right side on inspiration takes room from the left: this is ventricular interdependence. Inflammation of the sac (pericarditis) and fluid under pressure in it (tamponade) are the two halves of this deck."

